/**
 * Regenerates src/lib/countries.ts and src/lib/regions.ts from the
 * `country-state-city` package.
 *
 * Nothing under src/ may import `country-state-city`: the package is ~8.5 MB of
 * JS (every city on Earth). On the server it made every cold request exceed the
 * free-plan CPU limit; in the browser the forms downloaded 2.5 MB to list
 * countries and states (#60). The app only needs country names + ISO codes and
 * the states of the countries the form shows them for, so we snapshot those here.
 * tests/unit/location-data.test.ts fails if the snapshots drift from the package.
 *
 *   npx tsx scripts/gen-countries.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Country, State } from 'country-state-city';

// Countries whose state/province list the location field offers.
const COUNTRIES_WITH_REGIONS = [
  'US', 'CA', 'AU', 'DE', 'GB', 'FR', 'JP', 'CN', 'BR', 'MX', 'IN', 'IT', 'ES', 'NL', 'CH', 'AT', 'BE', 'PL', 'CZ', 'SE', 'NO', 'DK', 'NZ',
];

const lib = join(__dirname, '..', 'src', 'lib');

const countryRows = Country.getAllCountries().map((c) => `  ['${c.isoCode}', ${JSON.stringify(c.name)}],`);
writeFileSync(
  join(lib, 'countries.ts'),
  `// GENERATED by scripts/gen-countries.ts from country-state-city — do not edit.
// A server-safe snapshot of [ISO 3166-1 alpha-2, display name] pairs. See the
// generator for why nothing under src/ may import country-state-city directly.
export const COUNTRIES: ReadonlyArray<readonly [isoCode: string, name: string]> = [
${countryRows.join('\n')}
];
`,
);

const regionBlocks = COUNTRIES_WITH_REGIONS.map((code) => {
  const pairs = State.getStatesOfCountry(code).map((s) => `[${JSON.stringify(s.isoCode)},${JSON.stringify(s.name)}]`);
  return `  ${code}: [${pairs.join(',')}],`;
});
writeFileSync(
  join(lib, 'regions.ts'),
  `// GENERATED by scripts/gen-countries.ts from country-state-city — do not edit.
// [ISO 3166-2 subdivision code, display name] pairs for the countries whose states
// the location field offers. See the generator for why this is a snapshot.
export const REGIONS: Readonly<Record<string, ReadonlyArray<readonly [isoCode: string, name: string]>>> = {
${regionBlocks.join('\n')}
};
`,
);

console.log(`Wrote ${countryRows.length} countries and regions for ${COUNTRIES_WITH_REGIONS.length} countries`);
